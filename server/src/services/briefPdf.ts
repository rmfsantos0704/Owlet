import PDFDocument from "pdfkit";
import type { Response } from "express";
import { BRIEF_TEMPLATES, type BriefTemplateId } from "./briefTemplates.js";

// Built-in PDF fonts only cover Latin text, so anything else becomes "?" (same limit as the clip PDF).
const clean = (s: unknown) =>
  String(s ?? "").replace(/[^\x09\x0A\x0D\x20-\x7E\u00A0-\u00FF\u2018\u2019\u201C\u201D\u2013\u2014\u2026\u2022]/g, "?");

const fmt = (d?: Date | string) =>
  d ? new Date(d).toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" }) : "";

type BriefView = {
  title: string;
  template: string;
  question: string;
  updatedAt: string | Date;
  sources: { title: string; reference: string }[];
  sections: { title: string; blocks: { text: string; citations: { source: number }[] }[] }[];
};

export function streamBriefPdf(brief: BriefView, res: Response) {
  const slug = clean(brief.title).replace(/[^\w-]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 60) || "owlet-brief";
  res.setHeader("Content-Type", "application/pdf");
  res.setHeader("Content-Disposition", `attachment; filename="${slug}.pdf"`);

  const doc = new PDFDocument({ margin: 56, size: "A4" });
  doc.pipe(res);

  doc.font("Helvetica-Bold").fontSize(20).fillColor("#111111").text(clean(brief.title));
  const label = BRIEF_TEMPLATES[brief.template as BriefTemplateId]?.label ?? "Brief";
  doc.moveDown(0.3).font("Helvetica").fontSize(9.5).fillColor("#666666").text(`${label}  |  ${fmt(brief.updatedAt)}`);
  if (brief.question) {
    doc.moveDown(0.5).font("Helvetica-Oblique").fontSize(10.5).fillColor("#333333").text(`Research question: ${clean(brief.question)}`);
  }

  for (const section of brief.sections) {
    doc.moveDown(1).font("Helvetica-Bold").fontSize(13).fillColor("#111111").text(clean(section.title));
    doc.moveDown(0.3);
    for (const block of section.blocks) {
      const marks = [...new Set(block.citations.map((c) => c.source))].sort((a, b) => a - b).map((n) => `[${n}]`).join("");
      doc.font("Helvetica").fontSize(10.5).fillColor("#222222").text(`${clean(block.text)}${marks ? " " + marks : ""}`, { lineGap: 2 });
      doc.moveDown(0.5);
    }
  }

  doc.moveDown(1).font("Helvetica-Bold").fontSize(13).fillColor("#111111").text("References");
  doc.moveDown(0.3);
  brief.sources.forEach((source, i) => {
    doc.font("Helvetica").fontSize(10).fillColor("#222222").text(`[${i + 1}] ${clean(source.reference || source.title)}`, { lineGap: 2 });
    doc.moveDown(0.3);
  });

  doc.moveDown(1).font("Helvetica-Oblique").fontSize(8.5).fillColor("#888888")
    .text(`Generated by Owlet on ${fmt(new Date())}. AI-written text can contain mistakes: check each claim against its source before using it.`);
  doc.end();
}