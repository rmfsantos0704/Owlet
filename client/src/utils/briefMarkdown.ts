import type { Brief } from "../types";
import { templateLabel } from "../components/briefs/Templates";

// The brief as Markdown: numbered markers like [1] point to the reference list at the end.
export function briefToMarkdown(brief: Brief): string {
  const lines: string[] = [`# ${brief.title}`, ""];
  lines.push(`*${templateLabel(brief.template)} · ${new Date(brief.updatedAt).toLocaleDateString()}*`, "");
  if (brief.question) lines.push(`> Research question: ${brief.question}`, "");
  for (const section of brief.sections) {
    lines.push(`## ${section.title}`, "");
    for (const block of section.blocks) {
      const marks = [...new Set(block.citations.map((c) => c.source))].sort((a, b) => a - b).map((n) => `[${n}]`).join("");
      lines.push(`${block.text}${marks ? " " + marks : ""}`, "");
    }
  }
  lines.push("## References", "");
  brief.sources.forEach((s, i) => lines.push(`${i + 1}. ${s.reference || s.title}`));
  lines.push("", "---", "Generated by Owlet. AI-written text can contain mistakes: check each claim against its source.");
  return lines.join("\n");
}

export function downloadText(text: string, filename: string, type = "text/markdown") {
  const url = URL.createObjectURL(new Blob([text], { type: `${type};charset=utf-8` }));
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 10_000);
}