import PDFDocument from "pdfkit";
import type { Response } from "express";

// Built-in PDF fonts only cover Latin text, so anything else becomes "?".
const clean = (s: unknown) =>
  String(s ?? "").replace(/[^\x09\x0A\x0D\x20-\x7E\u00A0-\u00FF\u2018\u2019\u201C\u201D\u2013\u2014\u2026\u2022]/g, "?");

const fmt = (d?: Date | string) =>
  d ? new Date(d).toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" }) : "";

export function streamPdf(item: any, res: Response) {
  const slug =
    clean(item.source?.title).replace(/[^\w-]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 60) || "owlet-brief";
  res.setHeader("Content-Type", "application/pdf");
  res.setHeader("Content-Disposition", `attachment; filename="${slug}.pdf"`);

  const doc = new PDFDocument({ margin: 56, size: "A4" });
  doc.pipe(res);

  const heading = (t: string) =>
    doc.moveDown(0.9).font("Helvetica-Bold").fontSize(12).fillColor("#111111").text(t).moveDown(0.3);
  const body = (t: unknown) =>
    doc.font("Helvetica").fontSize(10.5).fillColor("#222222").text(clean(t) || "-", { lineGap: 2 });

  doc.font("Helvetica-Bold").fontSize(20).fillColor("#111111").text(clean(item.source?.title) || "Untitled");
  const meta = [item.source?.author, item.source?.domain, item.source?.publishedDate]
    .filter(Boolean).map(clean).join("  |  ");
  doc.moveDown(0.3).font("Helvetica").fontSize(9.5).fillColor("#666666").text(meta);
  if (item.source?.url) {
    doc.fillColor("#1a56db").text(clean(item.source.url), { link: item.source.url, underline: true });
  }
  if (item.tags?.length) {
    doc.moveDown(0.3).fillColor("#666666").text(item.tags.map((t: string) => "#" + clean(t)).join("  "));
  }

  heading("Summary");
  body(item.aiOutput?.summary);
  heading("Key arguments");
  body(item.aiOutput?.paraphrase);

  if (item.highlights?.length) {
    heading("Highlights");
    for (const h of item.highlights) {
      body(`"${h.text}"`);
      if (h.note) {
        doc.font("Helvetica-Oblique").fontSize(9.5).fillColor("#555555").text("Note: " + clean(h.note));
      }
      doc.moveDown(0.4);
    }
  }

  if (item.comments?.length) {
    heading("Comments");
    for (const c of item.comments) {
      body(c.text);
      doc.font("Helvetica").fontSize(8.5).fillColor("#888888").text(fmt(c.createdAt));
      doc.moveDown(0.4);
    }
  }

  heading("Citations");
  const cites: [string, string][] = [["APA", "apa"], ["MLA", "mla"], ["Chicago", "chicago"]];
  for (const [label, key] of cites) {
    doc.font("Helvetica-Bold").fontSize(9.5).fillColor("#111111").text(label);
    body(item.citations?.[key]);
    doc.moveDown(0.4);
  }

  doc.moveDown(1).font("Helvetica-Oblique").fontSize(8.5).fillColor("#888888")
    .text(`Generated by Owlet on ${fmt(new Date())}. Citations are auto-generated from page metadata; verify before submitting.`);
  doc.end();
}